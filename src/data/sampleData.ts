// Generate realistic historical daily/weekly trend points for the past 6 months
export function generateHistoricalPriceSeries(cropName: string, marketName: string = 'Akola APMC Mandi') {
  const baseMap: Record<string, number> = {
    Soybean: 4750,
    Cotton: 6900,
    Onion: 1600,
    Wheat: 2450,
    Tur: 8400,
    Chana: 5400,
    Maize: 2150,
    Tomato: 1400,
  };

  const base = baseMap[cropName] || 4800;
  const points: { date: string; price: number; arrivals: number; minPrice: number; maxPrice: number }[] = [];

  // 24 weeks of historical data up to late August 2026
  const startDate = new Date('2026-03-07');

  for (let i = 0; i < 25; i++) {
    const d = new Date(startDate);
    d.setDate(startDate.getDate() + i * 7);
    const dateStr = d.toISOString().split('T')[0];

    // realistic trend curve: slight dip around weeks 8-12, strong recovery going into August
    const wave = Math.sin(i / 3.5) * 180 + (i * 14);
    const noise = Math.sin(i * 13) * 45;
    const price = Math.round(base + wave + noise);
    const arrivals = Math.round(400 + Math.cos(i / 2) * 220 + Math.sin(i * 5) * 80);

    points.push({
      date: dateStr,
      price: price,
      minPrice: Math.round(price * 0.94),
      maxPrice: Math.round(price * 1.05),
      arrivals: arrivals,
    });
  }

  return points;
}
